#!/usr/bin/env node
/** Regenerates <campaign>/tables/prebuilt-crawlers.json (one legal pre-built per class) from tables/chargen-5e.json. */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadTables } from '../src/create/data.js';
import * as R from '../src/create/rules.js';
import { campaignDir } from '../src/session.js';

const dir = campaignDir(process.env);
const t = loadTables(dir);
const SPEC = [
  ['Barbarian', 'The Bouncer', 'Orc', 'Soldier', 'Throws people out of places. Now thrown into one.'],
  ['Bard', 'The Karaoke Menace', 'Human', 'Entertainer', 'One song, extremely loud.'],
  ['Cleric', 'The Youth Pastor', 'Dwarf', 'Acolyte', 'Prays fast, heals faster.'],
  ['Druid', 'The Houseplant Parent', 'Halfling', 'Hermit', 'Talks to the ficus. It talks back.'],
  ['Fighter', 'Mall Security', 'Human', 'Soldier', 'Has a flashlight and opinions.'],
  ['Monk', 'The Yoga Instructor', 'Elf', 'Wayfarer', 'Flexible in every sense.'],
  ['Paladin', 'The Hall Monitor', 'Dragonborn', 'Noble', 'Writes you up, then smites you.'],
  ['Ranger', 'The Park Ranger', 'Elf', 'Wayfarer', 'Knows which berries are fine.'],
  ['Rogue', 'The Couch-Surfer', 'Halfling', 'Criminal', 'Owns nothing. Steals everything.'],
  ['Sorcerer', 'The Gas-Station Prophet', 'Tiefling', 'Charlatan', 'Something fell out of them.'],
  ['Warlock', 'The Contract Reader', 'Gnome', 'Scribe', 'Read the fine print. Signed anyway.'],
  ['Wizard', 'The Grad Student', 'Human', 'Sage', 'Eleven years in; the thesis is fireballs.'],
];
const out = [];
for (const [cls, label, species, background, blurb] of SPEC) {
  const d = { class: cls, species, background, classChoices: {}, cart: [] };
  for (const s of ['S5', 'S6', 'S7', 'S8', 'S9', 'S10', 'S11']) R.autoPick(s, d, t);
  d.orders = 'Stay near the party, avoid fights I cannot win, and head for the nearest saferoom.';
  d.reactions = 'Opportunity Attacks: on';
  const errs = R.validateDraft({ ...d, name: 'x', look: 'x', hook: 'x', backstory: 'x', tags: ['a', 'b', 'c'] }, t).filter((e) => !['S1'].includes(e.screen));
  if (errs.length) throw new Error(`${label}: ${errs.map((e) => `${e.screen} ${e.msg}`).join('; ')}`);
  out.push({ id: cls.toLowerCase(), label, blurb, class: cls, species, speciesSub: d.speciesSub ?? null, background, asi: d.asi, extraFeat: d.extraFeat ?? null, classChoices: d.classChoices, method: d.method, base: d.base, classSkills: d.classSkills, speciesSkill: d.speciesSkill ?? null, featSkills: d.featSkills ?? [], languages: d.languages, expertise: d.expertise ?? [], masteries: d.masteries ?? [], kitClass: 'A', kitBg: 'A', cart: d.cart, spells: d.spells ?? null, orders: d.orders, reactions: d.reactions });
}
writeFileSync(join(dir, 'tables', 'prebuilt-crawlers.json'), JSON.stringify({ meta: { version: '0.1.0', note: 'Generated by scripts/gen-prebuilt.js (Borent). Syndicate: reword labels/blurbs freely; keep ids and mechanical fields or regenerate.' }, crawlers: out }, null, 1));
console.log(`wrote ${out.length} pre-builts`);
